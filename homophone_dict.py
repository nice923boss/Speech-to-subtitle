# - 本詞典只列「高信心」修正，低信心的語境相關修正不在此列
# - 定期根據實際辨識結果擴充本詞典
#
# 統計資訊：
# - GLOBAL_FIXES:  {count_g} 條
# - DOMAIN_FIXES:  {count_d} 條（合計所有領域）
# - CN_TO_TW:      {count_c} 條
# - EN_FIXES:      {count_e} 條
# - 總計:          {count_t} 條
#

def print_stats():
    """印出詞典統計資訊"""
    count_g = len(GLOBAL_FIXES)
    count_d = sum(len(v) for v in DOMAIN_FIXES.values())
    count_c = len(CN_TO_TW)
    count_e = len(EN_FIXES)
    count_t = count_g + count_d + count_c + count_e

    print(f"GLOBAL_FIXES:  {count_g} 條")
    print(f"DOMAIN_FIXES:  {count_d} 條（合計所有領域）")
    for domain, fixes in DOMAIN_FIXES.items():
        print(f"  - {domain}: {len(fixes)} 條")
    print(f"CN_TO_TW:      {count_c} 條")
    print(f"EN_FIXES:      {count_e} 條")
    print(f"總計:          {count_t} 條")


def build_all_homophones(domains: list[str] | None = None) -> dict[str, str]:
    """合併 GLOBAL_FIXES + 指定領域的同音字修正。

    這是管線中同音字修正的 **單一來源**，供以下模組使用：
    - final_sanitize.py（Step 7 自動修正）
    - validate_final.py（Step 8 品質檢查）
    - post_mfa_cleanup.py（Step 6 嫌疑標記）

    Args:
        domains: 指定領域清單（如 ["finance", "legal"]）。
                 預設 None = 全部領域。

    GLOBAL_FIXES 永遠載入；DOMAIN_FIXES 按 domains 篩選後載入。
    DOMAIN_FIXES 後載入，同鍵時領域修正優先。

    刻意不包含 CN_TO_TW 和 EN_FIXES：
    - CN_TO_TW 由 OpenCC s2twp + TWPhrases 攔截（術語偏好，非同音字）。
    - EN_FIXES 不適用於中文淨化階段。
    """
    combined: dict[str, str] = {}
    combined.update(GLOBAL_FIXES)
    target = domains if domains is not None else list(DOMAIN_FIXES.keys())
    for domain in target:
        if domain in DOMAIN_FIXES:
            combined.update(DOMAIN_FIXES[domain])
    return combined


def build_suspect_list(domains: list[str] | None = None) -> list[tuple[str, str]]:
    """建構嫌疑清單，供 post_mfa_cleanup.py Step 6 標記用。

    取代原本 post_mfa 內部的 HOMOPHONE_PAIRS，實現單一資料來源。
    回傳 [(wrong, right), ...] 列表（按 wrong 長度降冪排序，長優先匹配）。
    """
    all_homophones = build_all_homophones(domains)
    return sorted(all_homophones.items(), key=lambda x: -len(x[0]))


